//! `TabStrip` — строка вкладок панели (ADR-0024, ADR-0032): вкладки со значком типа и точкой
//! статуса, справа нагрузка, кнопки «Разделить», «Развернуть панель» и меню «…». Режим по ширине
//! выбирает чистая функция [`layout::regime`]: всё видно, нагрузка в заголовке меню «…» или
//! прокрутка вкладок, кнопки не скрываются.
//!
//! Чистая часть — модель с разницей состояний ([`model`]) и геометрия ([`layout`]); её тестирует
//! `make check`. Вид применяет операции к AppKit: виды вкладок переиспользуются по id, прокрутка к
//! выбранной вкладке анимируется только при обычном движении, цвета меняются без неявных анимаций.

pub(crate) mod layout;
pub(crate) mod model;
mod view;

pub use view::{ButtonFacts, TabFacts, TabStrip, TabStripFacts};
